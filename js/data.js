/* 쯔쯔가무시증 계절 계수 (주차 기준, 10~11월 피크) */
function seasonFactor(w){
  const curve = {1:.10,4:.13,7:.19,10:.24,13:.29,16:.32,19:.34,22:.32,25:.29,28:.30,31:.33,34:.42,37:.62,40:.88,42:1.00,44:.96,46:.78,48:.60,50:.36,52:.16};
  const keys = Object.keys(curve).map(Number).sort((a,b)=>a-b);
  if(w<=keys[0]) return curve[keys[0]];
  if(w>=keys[keys.length-1]) return curve[keys[keys.length-1]];
  for(let i=0;i<keys.length-1;i++){
    if(w>=keys[i]&&w<=keys[i+1]){
      const t=(w-keys[i])/(keys[i+1]-keys[i]);
      return curve[keys[i]]*(1-t)+curve[keys[i+1]]*t;
    }
  }
  return .5;
}

